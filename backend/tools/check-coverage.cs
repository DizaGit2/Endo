// Coverage gate for the Lumen backend.
//
//   dotnet test backend/Lumen.slnx --settings backend/coverlet.runsettings --collect:"XPlat Code Coverage" --nologo --results-directory TestResults
//   dotnet run backend/tools/check-coverage.cs
//
// A .NET 10 file-based app: no project, no new NuGet package, `dotnet run` is the whole toolchain.
// Reads every coverage.cobertura.xml under the results directory, merges them, and reports TWO
// figures against ONE denominator split by path:
//
//   * whole tree     — every instrumented line under backend/src
//   * hand-written   — the same, minus generated EF migrations and LumenDbContextModelSnapshot.cs
//
// The gate is the hand-written figure (plan G15). BOTH are always printed, because the whole point of
// G15 is that nobody should later read "97%" as whole-tree coverage.
//
// WHY THIS FILE EXISTS AT ALL, rather than coverlet's ExcludeByFile:
//
//   1. ExcludeByFile is a glob. The client's gate was written with a glob first and it was WRONG: `*`
//      did not cross `/` the way the author assumed, nested generated files stayed in the denominator,
//      and the gate reported 58.6% against a true 97.60% until a review caught it. So the exclusion
//      here is an ordinal PATH match on a normalized path, with a leading separator forced on, and it
//      is exercised by the fixtures in `--self-test`.
//   2. Excluding at collection time cannot report both figures — the excluded lines are simply gone
//      from the report. Partitioning after the fact reports both from one run.
//
// WHAT IS EXCLUDED, and why it is exactly this:
//
//   backend/src/**/Migrations/**            EF-generated: Up/Down, the per-migration .Designer.cs
//   backend/src/**/LumenDbContextModelSnapshot.cs   snapshot regenerated by `dotnet ef`
//
// Neither is executed by any test — LiveStack applies migrations out of process via `dotnet ef` — so
// they report zero hits forever, and at T20 they are 4,340 of 8,347 instrumented lines (52%). Nothing
// else is excluded. In particular the source-generated RegexGenerator output under obj/ is LEFT IN
// even though it is machine-written, because dropping it would RAISE the reported figure and the one
// thing a coverage gate must never do is move its own denominator to reach its own threshold.
//
// Usage:
//   dotnet run backend/tools/check-coverage.cs [-- <results-dir>] [--threshold <pct>] [--self-test]

using System.Globalization;
using System.Xml.Linq;

const double DefaultThreshold = 70.0;

var resultsDirectory = "TestResults";
var threshold = DefaultThreshold;

for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--self-test":
            return SelfTest();
        case "--threshold" when i + 1 < args.Length:
            threshold = double.Parse(args[++i], CultureInfo.InvariantCulture);
            break;
        default:
            resultsDirectory = args[i];
            break;
    }
}

return Gate(resultsDirectory, threshold, quiet: false);

